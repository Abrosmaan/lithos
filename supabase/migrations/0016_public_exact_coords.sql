-- LITHOS — 0016 точные координаты в публичной витрине (T7.3, поток A). Идемпотентно, schema-qualified.
--
-- СМЕНА МОДЕЛИ ПРИВАТНОСТИ (решение владельца, 2026-10-03, отменяет прежнее).
-- Прежняя модель (T6.0-fixes-and-social.md §2.1–2.2, миграция 0007): наружу уходит только `cell_id`
-- (geohash-6, ~1,2 км), точные координаты принципиально не публикуются — это было явным, «не обсуждаемым»
-- правилом и было закреплено тестом-инвариантом (apps/mobile/src/lib/publish.test.ts), который падал при
-- одном появлении lat/lng в тексте этой самой миграции.
--
-- Новое решение: опубликованная находка показывается на карте точными координатами, как в iNaturalist,
-- а не центром ячейки. Владелец принял это осознанно, зная цену: точное место находки становится видно
-- ВСЕМ пользователям приложения, и для уже опубликованной карточки это решение необратимо — «забрать
-- обратно» точные координаты из показанной карты нельзя (можно только снять публикацию целиком).
-- На момент этой миграции в базе 0 опубликованных карточек (проверено перед написанием) — то есть задним
-- числом ничего не раскрывается, разом с этим решением ничья существующая находка не обнажается.
--
-- Что НЕ меняется: все условия отбора (published/not hidden/verification<>pending_review), остальной набор
-- колонок, грант select только для authenticated (не anon, не public), RPC publish_card/report_card/
-- public_photo_path и политика storage.objects — всё из 0007/0010/0011/0012 не трогается.
--
-- `cell_id` остаётся колонкой представления: он нужен клиенту не как замена точных координат (это было
-- ровно то, от чего теперь отказались), а как ключ группировки «здесь находили другие» в дневнике места
-- (T6.1-D, lib/publish.ts/public-map.ts) — эта механика не про приватность, а про агрегацию по ячейке.
--
-- Представление пересоздаётся (drop + create), а не "create or replace": новые колонки нужны рядом с
-- `cell_id`, а Postgres разрешает "or replace" только добавление колонок в конец списка. Зависимых SQL-
-- объектов у lithos.public_finds нет (проверено: ни видов, ни правил, ни функций, ссылающихся на
-- представление, не существует) — дроп безопасен. Права после пересоздания выдаются явно заново ниже.
-- ============================================================================

drop view if exists lithos.public_finds;

create view lithos.public_finds as
select
  c.id,
  c.rock_class,
  c.tier,
  c.score,
  c.lore,
  c.name,
  c.user_name,
  c.cell_id,
  c.lat,
  c.lng,
  c.created_at,
  c.published_at,
  u.display_name as author_name
from lithos.cards c
join lithos.users u on u.id = c.user_id
where c.published
  and not c.hidden
  and c.verification <> 'pending_review';

comment on view lithos.public_finds is 'Публичная витрина (T7.3, решение владельца 2026-10-03). Отдаёт точные lat/lng опубликованной карточки — это сознательная смена модели приватности (см. шапку миграции 0016), а не недосмотр. Колонки сверх согласованного списка из data-map.md/T6.0 §2.1 (кроме lat/lng) по-прежнему не добавлять.';

grant select on lithos.public_finds to authenticated;
