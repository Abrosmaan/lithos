-- ============================================================================
-- LITHOS — 0011 корневая причина дефекта, который чинила 0010 (правка по ревью потока D).
-- Идемпотентно, schema-qualified.
--
-- Postgres выдаёт EXECUTE на каждую новую функцию роли PUBLIC. Из-за этого 0007 нечаянно открыла
-- lithos.public_photo_path анонимному вызывающему, и 0010 отзывала право у трёх функций вручную.
-- Чтобы следующая security-definer-функция не повторила тот же класс дыры при забытом revoke, право
-- по умолчанию отзывается для всех будущих функций схемы lithos.
--
-- ВАЖНО для будущих миграций: после этого файла каждой новой функции нужен явный
--   grant execute on function lithos.<имя>(<типы>) to authenticated;
-- Это касается и функций-помощников внутри RLS-политик (например по образцу lithos.current_user_id):
-- политика выполняется от лица вызывающего, и без явного гранта запросы упадут «permission denied».
-- Отказ будет громким и сразу, а не тихой утечкой — ради этого размен и делается.
--
-- Действует только на объекты, создаваемые той же ролью, что выполняет этот файл (роль миграций,
-- scripts/db-migrate.mjs). На уже существующие функции не влияет: у них права те, что выданы раньше,
-- и массово отзывать их здесь нельзя — lithos.current_user_id() вызывается из RLS-политик, и отзыв
-- у PUBLIC без компенсирующего гранта сломал бы доступ к собственным данным.
-- ============================================================================

alter default privileges in schema lithos revoke execute on functions from public;
