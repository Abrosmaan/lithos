// Кластеризация чужих находок по масштабу карты (T7.3-C). Раньше карта группировала чужие находки по
// центру ячейки geohash-6 (lib/public-map.ts), и groupByLocation (geo-math.ts) — группировка по точно
// совпадающим координатам — этого было достаточно: все находки одной ячейки получали один и тот же центр.
// Теперь находка стоит по своим точным lat/lng (решение владельца, 2026-10-03), и с ростом числа публикаций
// совпадающих координат почти не будет — без кластеризации карта превратится в кашу из маркеров впритык.
//
// Решение: сетка, размер ячейки которой пропорционален видимому охвату карты (span = наибольшая из
// latitudeDelta/longitudeDelta региона). Далеко — крупная ячейка, кластеры большие; при приближении span
// уменьшается, ячейка мельчает, кластеры распадаются, пока на сильном зуме каждая находка не станет своим
// маркером. Своя реализация без библиотек кластеризации (CLAUDE.md — новых зависимостей не подключать).
import { GROUP_PRECISION } from './geo-math';

export interface ClusterGroup<T> {
  /** Центроид входящих точек — в отличие от groupByLocation находки в кластере физически не совпадают,
   *  маркер должен сесть между ними, а не на случайно первую. */
  lat: number;
  lng: number;
  items: T[];
}

/** На сколько ячеек сетки делим видимый охват карты. Не балансовое число (CLAUDE.md — про score/тиры) —
 *  инженерная настройка «насколько быстро кластеры распадаются при приближении». */
export const CLUSTER_GRID_DIVISIONS = 24;

/** Пол размера ячейки — на максимальном зуме (span → 0) ячейка не должна стать бесконечно малой: тогда
 *  кластеризация выключилась бы даже для двух находок в одной физической точке. То же разрешение, что у
 *  групировки совпадающих координат (~1 м). */
export const MIN_CLUSTER_CELL = 10 ** -GROUP_PRECISION;

/** Размер стороны ячейки сетки для данного охвата (в градусах). */
export function clusterCellSize(span: number): number {
  return Math.max(MIN_CLUSTER_CELL, span / CLUSTER_GRID_DIVISIONS);
}

/**
 * Группирует точки в кластеры по сетке; размер ячейки зависит от `span` — наибольшей из
 * latitudeDelta/longitudeDelta видимого региона карты (то есть от текущего зума). Порядок кластеров — по
 * первому вхождению точки, как в groupByLocation.
 *
 * Два известных ограничения простой сетки, оба осознанные (библиотеку кластеризации не подключаем):
 * 1. Две очень близкие точки по разные стороны границы ячейки могут не слиться в один кластер.
 * 2. Ключ ячейки строится из сырой долготы, поэтому находки по разные стороны антимеридиана
 *    (−179,999 и 179,999) попадут в разные кластеры, хотя физически стоят рядом. Подгрузка по области
 *    этот разрыв обрабатывает, группировка — нет. Чтобы это проявилось, в одном кадре должны оказаться
 *    находки с обеих сторон линии перемены даты.
 */
export function clusterByZoom<T extends { lat: number; lng: number }>(points: readonly T[], span: number): ClusterGroup<T>[] {
  const cell = clusterCellSize(Math.max(0, span));
  const order: string[] = [];
  const groups = new Map<string, T[]>();
  for (const p of points) {
    const key = `${Math.floor(p.lat / cell)}|${Math.floor(p.lng / cell)}`;
    const list = groups.get(key);
    if (list) list.push(p);
    else { groups.set(key, [p]); order.push(key); }
  }
  return order.map((key) => {
    const items = groups.get(key)!;
    const lat = items.reduce((s, p) => s + p.lat, 0) / items.length;
    const lng = items.reduce((s, p) => s + p.lng, 0) / items.length;
    return { lat, lng, items };
  });
}
